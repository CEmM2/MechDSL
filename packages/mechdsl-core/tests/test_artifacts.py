    def test_golden_load_missing_file(self, tmp_path: Path) -> None:
        """Missing golden file raises FileNotFoundError with instructions."""
        with pytest.raises(FileNotFoundError, match="Golden file not found"):
            _load_golden(tmp_path, "nonexistent.npz")

    def test_golden_load_missing_contains_regen_hint(self, tmp_path: Path) -> None:
        """Error message includes the regeneration command."""
        with pytest.raises(FileNotFoundError, match="generate_golden"):
            _load_golden(tmp_path, "nonexistent.npz")

    def test_golden_load_corrupt_file(self, tmp_path: Path) -> None:
        """Corrupt .npz file raises an error on load."""
        corrupt_path = tmp_path / "corrupt.npz"
        corrupt_path.write_bytes(b"this is not a valid npz file")

        with pytest.raises((ValueError, OSError)):
            _load_golden(tmp_path, "corrupt.npz")

