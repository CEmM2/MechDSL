"""Tests for artifact bundle serialisation and golden-file regression.

Golden files are generated by ``tests/generate_golden.py`` and stored in
``tests/golden/`` as compressed numpy archives (.npz).  These tests verify
that fresh reference solver runs produce output matching the stored golden
data to within numerical tolerance.

Regenerate golden files intentionally with:
    PYTHONPATH=packages/mechdsl-core uv run python packages/mechdsl-core/tests/generate_golden.py
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import numpy as np
import pytest

from mechdsl.symbolic.models.j2_power_law import J2PowerLawMaterial
from tests.ref.ref_hex8_elastic import generate_hex8_mesh, solve_elastic
from tests.ref.ref_hex8_plastic import solve_plastic

if TYPE_CHECKING:
    from pathlib import Path

    from numpy.typing import NDArray


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

# Tolerance for displacement comparison (spec: < 1e-10 relative).
_RTOL_DISP = 1e-10
_ATOL_DISP = 1e-14  # absolute floor for near-zero values
# Newton residual tails are sensitive to BLAS / platform roundoff once the solve
# is already in the ~1e-11 range, so keep a tiny absolute floor for the final
# iterations while preserving strict relative checks on the larger entries.
_RTOL_RESIDUAL = 1e-8
_ATOL_RESIDUAL = 2e-11


def _load_golden(golden_dir: Path, name: str) -> dict[str, NDArray]:
    """Load a golden .npz file and return its contents as a dict.

    Raises
    ------
    FileNotFoundError
        With a clear message pointing to the regeneration script.
    """
    path = golden_dir / name
    if not path.exists():
        msg = (
            f"Golden file not found: {path}\n"
            "Regenerate with:\n"
            "  PYTHONPATH=packages/mechdsl-core "
            "uv run python packages/mechdsl-core/tests/generate_golden.py"
        )
        raise FileNotFoundError(msg)
    return dict(np.load(path, allow_pickle=False))


def _run_elastic_cantilever() -> tuple[NDArray, list[float], NDArray, NDArray]:
    """Reproduce the elastic cantilever problem from golden generation.

    Returns (displacement, residual_history, coords, conn).
    """
    nx, ny, nz = 4, 2, 1
    Lx, Ly, Lz = 4.0, 2.0, 1.0
    coords, conn = generate_hex8_mesh(nx, ny, nz, Lx, Ly, Lz)
    n_nodes = coords.shape[0]

    E_young = 200.0e3
    nu = 0.3
    lam = E_young * nu / ((1 + nu) * (1 - 2 * nu))
    mu = E_young / (2 * (1 + nu))

    bc_mask = np.zeros((n_nodes, 3), dtype=bool)
    bc_values = np.zeros((n_nodes, 3), dtype=np.float64)
    left_nodes = np.where(np.abs(coords[:, 0]) < 1e-12)[0]
    bc_mask[left_nodes, :] = True

    f_ext = np.zeros((n_nodes, 3), dtype=np.float64)
    right_top = np.where(
        (np.abs(coords[:, 0] - Lx) < 1e-12)
        & (np.abs(coords[:, 1] - Ly) < 1e-12)
        & (np.abs(coords[:, 2] - Lz) < 1e-12)
    )[0]
    assert len(right_top) == 1
    f_ext[right_top[0], 2] = -10.0

    u, residuals = solve_elastic(
        coords,
        conn,
        lam,
        mu,
        bc_mask,
        bc_values,
        f_ext,
        tol=1e-8,
        max_iter=50,
        cg_tol=1e-10,
        cg_max_iter=2000,
    )
    return u, residuals, coords, conn


def _run_plastic_uniaxial() -> tuple[NDArray, NDArray, list[list[float]], NDArray, NDArray]:
    """Reproduce the plastic uniaxial problem from golden generation.

    Returns (displacement, alpha, residual_history, coords, conn).
    """
    nx, ny, nz = 2, 1, 1
    Lx, Ly, Lz = 2.0, 1.0, 1.0
    coords, conn = generate_hex8_mesh(nx, ny, nz, Lx, Ly, Lz)
    n_nodes = coords.shape[0]

    mat = J2PowerLawMaterial(E=200.0e3, nu=0.3, sigma_y0=250.0, K=1000.0, n=1.0)

    bc_mask = np.zeros((n_nodes, 3), dtype=bool)
    bc_values = np.zeros((n_nodes, 3), dtype=np.float64)
    left_nodes = np.where(np.abs(coords[:, 0]) < 1e-12)[0]
    bc_mask[left_nodes, :] = True

    right_nodes = np.where(np.abs(coords[:, 0] - Lx) < 1e-12)[0]
    bc_mask[right_nodes, 0] = True
    bc_values[right_nodes, 0] = 0.005 * Lx

    f_ext = np.zeros((n_nodes, 3), dtype=np.float64)

    u, history, residual_history = solve_plastic(
        coords,
        conn,
        mat,
        bc_mask,
        bc_values,
        f_ext,
        n_steps=5,
        tol=1e-8,
        max_iter=50,
        cg_tol=1e-10,
        cg_max_iter=2000,
    )
    return u, history.alpha_current, residual_history, coords, conn


