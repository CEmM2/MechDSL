# ===========================================================================
# Test 4: Drift detection — perturbed golden
# ===========================================================================


class TestGoldenDriftDetection:
    """Verify that the test infrastructure catches deliberate perturbations."""

    def test_golden_drift_detection(self, golden_dir: Path, tmp_path: Path) -> None:
        """Intentionally perturb golden displacement and verify detection.

        Creates a temporary copy of the golden file with the displacement
        perturbed by 1e-6, then checks that comparison would fail.
        """
        # Load the real golden data
        original = _load_golden(golden_dir, "elastic_cantilever.npz")

        perturbed_dir = tmp_path / "golden_perturbed"
        perturbed_dir.mkdir()

        perturbed_disp = original["displacement"].copy()
        perturbed_disp[0, 0] += 1e-6  # add detectable perturbation

        np.savez_compressed(
            perturbed_dir / "elastic_cantilever.npz",
            displacement=perturbed_disp,
            residual_history=original["residual_history"],
            coords=original["coords"],
            conn=original["conn"],
            lam=original["lam"],
            mu=original["mu"],
        )

        # Run fresh solver
        u_fresh, _res, _coords, _conn = _run_elastic_cantilever()

        # The comparison should FAIL against the perturbed golden data
        perturbed_golden = _load_golden(perturbed_dir, "elastic_cantilever.npz")
        with pytest.raises(AssertionError, match="Perturbed golden"):
            np.testing.assert_allclose(
                u_fresh,
                perturbed_golden["displacement"],
                rtol=_RTOL_DISP,
                atol=_ATOL_DISP,
                err_msg="Perturbed golden must not match fresh solve",
            )


