# Test 6: Necking bar golden regression
# ===========================================================================


class TestGoldenNeckingBarMatches:
    """Verify necking bar reference data integrity (Task P3-3).

    Acceptance criteria covered:
      AC1: Reference data contains displacement and force arrays
      AC2: Reference data includes mesh_params and material_params
      AC3: Fine mesh solution converges at all load steps
    """

    def test_golden_necking_bar_keys(self, golden_dir: Path) -> None:
        """Verify reference .npz contains required keys.

        Acceptance criterion: P3-3 AC1 + AC2
        Passes when: displacement, force, mesh, and material params present.
        """
        path = golden_dir / "necking_bar_reference.npz"
        if not path.exists():
            pytest.skip("golden file not generated")
        data = np.load(path)

        # Displacement + load-displacement curve
        assert "displacement" in data.files
        assert "force_history" in data.files
        assert "disp_history" in data.files

        # Mesh
        assert "coords" in data.files
        assert "conn" in data.files
        for key in ("nx", "ny", "nz"):
            assert key in data.files, f"missing mesh density key: {key}"

        # Material params (J2 power-law)
        for key in ("E", "nu", "sigma_y0", "K", "n_hard"):
            assert key in data.files, f"missing material param: {key}"

        # Residual history (ragged storage, same pattern as plastic_uniaxial)
        assert "residual_history_flat" in data.files
        assert "residual_step_lengths" in data.files

        # Shape consistency
        u = data["displacement"]
        coords = data["coords"]
        assert u.shape == coords.shape, (
            f"displacement shape {u.shape} != coords shape {coords.shape}"
        )

        n_steps = int(data["residual_step_lengths"].shape[0])
        assert data["force_history"].shape == (n_steps,)
        assert data["disp_history"].shape == (n_steps,)

    def test_golden_necking_bar_convergence(self, golden_dir: Path) -> None:
        """Verify Newton converged at every load step.

        Acceptance criterion: P3-3 AC3
        Passes when: each step's final residual is below a reasonable
        absolute floor and the residual sequence makes progress from its
        initial value.
        """
        path = golden_dir / "necking_bar_reference.npz"
        if not path.exists():
            pytest.skip("golden file not generated")
        data = np.load(path)

        flat = data["residual_history_flat"]
        lengths = data["residual_step_lengths"]

        # Reconstruct per-step residual sequences from ragged storage
        idx = 0
        for step_idx, length in enumerate(lengths):
            step_residuals = flat[idx : idx + int(length)]
            idx += int(length)

            assert len(step_residuals) >= 1, f"step {step_idx} has no residuals"

            # Final residual must be small enough that Newton did not diverge.
            # The ref solver uses tol=1e-8 * R0 so the final absolute residual
            # should be orders of magnitude below the initial.
            r0 = float(step_residuals[0])
            rf = float(step_residuals[-1])
            if r0 > 1e-15:
                reduction = rf / r0
                assert reduction < 1e-6, (
                    f"step {step_idx}: Newton did not reduce residual enough "
                    f"(R0={r0:.3e}, Rf={rf:.3e}, reduction={reduction:.3e})"
                )

        # Monotonic loading → monotonic displacement history
        disp = data["disp_history"]
        assert np.all(np.diff(disp) > 0), "disp_history should be strictly increasing"

        # Non-trivial plastic deformation — force history should show growth
        # beyond the initial elastic response (it's not required to be monotonic
        # everywhere, but the final force must be greater than the first).
        force = np.abs(data["force_history"])
        assert force[-1] > force[0], (
            f"final reaction force {force[-1]:.3e} not greater than "
            f"initial {force[0]:.3e} — expected growth under monotonic loading"
        )
