    def test_golden_plastic_alpha(self, golden_dir: Path) -> None:
        """Equivalent plastic strain matches golden."""
        golden = _load_golden(golden_dir, "plastic_uniaxial.npz")
        _u, alpha_fresh, _res, _coords, _conn = _run_plastic_uniaxial()

        np.testing.assert_allclose(
            alpha_fresh,
            golden["alpha"],
            rtol=_RTOL_DISP,
            atol=_ATOL_DISP,
            err_msg="Plastic alpha (equiv. plastic strain) does not match golden data",
        )

    def test_golden_plastic_residual_history(self, golden_dir: Path) -> None:
        """Residual history per step matches golden."""
        golden = _load_golden(golden_dir, "plastic_uniaxial.npz")
        _u, _alpha, residuals_fresh, _coords, _conn = _run_plastic_uniaxial()

        # Reconstruct flat residual array
        flat_fresh = np.concatenate([np.array(step, dtype=np.float64) for step in residuals_fresh])
        step_lengths_fresh = np.array([len(step) for step in residuals_fresh], dtype=np.int64)

        np.testing.assert_array_equal(
            step_lengths_fresh,
            golden["residual_step_lengths"],
            err_msg="Number of Newton iterations per step differs from golden",
        )
        np.testing.assert_allclose(
            flat_fresh,
            golden["residual_flat"],
            rtol=_RTOL_RESIDUAL,
            atol=_ATOL_RESIDUAL,
            err_msg="Plastic residual history does not match golden data",
        )

    def test_golden_plastic_mesh_unchanged(self, golden_dir: Path) -> None:
        """Mesh in golden file is consistent with fresh generation."""
        golden = _load_golden(golden_dir, "plastic_uniaxial.npz")
        _u, _alpha, _res, coords_fresh, conn_fresh = _run_plastic_uniaxial()

