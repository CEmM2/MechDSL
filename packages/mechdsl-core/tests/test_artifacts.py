# ===========================================================================
# Test 2: Elastic golden regression
# ===========================================================================


class TestGoldenElasticMatches:
    """Fresh elastic solver run must match the stored golden data."""

    def test_golden_elastic_displacement(self, golden_dir: Path) -> None:
        """Displacement field matches golden to < 1e-10 relative tolerance."""
        golden = _load_golden(golden_dir, "elastic_cantilever.npz")
        u_fresh, _res, _coords, _conn = _run_elastic_cantilever()

        np.testing.assert_allclose(
            u_fresh,
            golden["displacement"],
            rtol=_RTOL_DISP,
            atol=_ATOL_DISP,
            err_msg="Elastic displacement field does not match golden data",
        )

    def test_golden_elastic_residual_history(self, golden_dir: Path) -> None:
        """Residual history matches golden (same convergence path)."""
        golden = _load_golden(golden_dir, "elastic_cantilever.npz")
        _u, residuals_fresh, _coords, _conn = _run_elastic_cantilever()

        residuals_arr = np.array(residuals_fresh, dtype=np.float64)
        np.testing.assert_allclose(
            residuals_arr,
            golden["residual_history"],
            rtol=_RTOL_RESIDUAL,
            atol=_ATOL_RESIDUAL,
            err_msg="Elastic residual history does not match golden data",
        )

    def test_golden_elastic_mesh_unchanged(self, golden_dir: Path) -> None:
        """Mesh (coords + connectivity) in golden file is consistent."""
        golden = _load_golden(golden_dir, "elastic_cantilever.npz")
        _u, _res, coords_fresh, conn_fresh = _run_elastic_cantilever()

        np.testing.assert_array_equal(
            coords_fresh,
            golden["coords"],
            err_msg="Mesh coordinates differ from golden — problem setup changed?",
        )
        np.testing.assert_array_equal(
            conn_fresh,
            golden["conn"],
            err_msg="Element connectivity differs from golden — problem setup changed?",
        )


