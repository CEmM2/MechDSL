class TestGoldenPlasticMatches:
    """Fresh plastic solver run must match the stored golden data."""

    def test_golden_plastic_displacement(self, golden_dir: Path) -> None:
        """Displacement field matches golden to < 1e-10 relative tolerance."""
        golden = _load_golden(golden_dir, "plastic_uniaxial.npz")
