        golden = _load_golden(golden_dir, "plastic_uniaxial.npz")

        assert float(golden["E"]) == pytest.approx(200.0e3)
        assert float(golden["nu"]) == pytest.approx(0.3)
        assert float(golden["sigma_y0"]) == pytest.approx(250.0)
