def _raw_global_matvec(
    u: np.ndarray,
    v: np.ndarray,
    coords: np.ndarray,
    conn: np.ndarray,
    lam: float,
    mu: float,
) -> np.ndarray:
    """Global tangent matvec WITHOUT BC enforcement (newton_solve wraps BCs)."""
    n_nodes = coords.shape[0]
    Kv = np.zeros((n_nodes, 3), dtype=np.float64)
    for e in range(conn.shape[0]):
        nodes = conn[e]
        Kv_e = ref_elem_tangent_matvec(u[nodes], coords[nodes], v[nodes], lam, mu)
        for a in range(8):
            Kv[nodes[a]] += Kv_e[a]
    return Kv


def _build_small_elastic_patch() -> dict:
    """Small linear-elastic Hex8 patch — single 1x1x1 element under tiny extension.

    Why this fixture?
      * Single Hex8 element keeps the test under 1s (no @slow marker needed).
      * SVK at small strain is effectively linear elasticity, so Newton
        converges in 1-2 iterations — matching the stub's "<=2 iterations"
        wording most precisely.
      * Reference assembly uses the handwritten ``ref_hex8_elastic`` kernels
        (the ``algo2code`` PCG is the *only* generated component).

    BCs:
      * Left face (x=0) fully clamped (3 DOFs per node x 4 nodes = 12 fixed).

    Loading:
      * Tiny tensile force on each right-face node (x=Lx). The total load is
        small enough that the geometric / nonlinear contribution to SVK is
        ~1e-9 of the linear part, so Newton lands in 1 iteration.
    """
    # Single 1x1x1 Hex8 element
    coords, conn = generate_hex8_mesh(1, 1, 1, 1.0, 1.0, 1.0)
    n_nodes = coords.shape[0]

    # Material: E=1000, nu=0.3 -> Lame parameters
    E_mod, nu = 1000.0, 0.3
    lam = E_mod * nu / ((1 + nu) * (1 - 2 * nu))
    mu = E_mod / (2 * (1 + nu))

    # BC: clamp left face (x=0)
    bc_mask = np.zeros((n_nodes, 3), dtype=bool)
    left_nodes = np.where(np.abs(coords[:, 0]) < 1e-12)[0]
    bc_mask[left_nodes, :] = True

    # Tensile load on right face: tiny so SVK ~= linear elasticity.
    f_ext = np.zeros((n_nodes, 3), dtype=np.float64)
    right_nodes = np.where(np.abs(coords[:, 0] - 1.0) < 1e-12)[0]
    for nd in right_nodes:
        f_ext[nd, 0] = 1e-3  # tiny tensile force per node

    return {
        "coords": coords,
        "conn": conn,
        "lam": lam,
        "mu": mu,
        "bc_mask": bc_mask,
        "f_ext": f_ext,
        "n_nodes": n_nodes,
    }


def _newton_run_with(
    s: dict,
    linear_solver: LinearSolverInterface,
) -> tuple[NewtonResult, np.ndarray]:
    """Run ``newton_solve`` on the elastic patch with the supplied linear solver.

    Returns (result, final_displacement). The displacement array is built
    fresh per call so the two sweeps cannot cross-contaminate.
    """
    u = np.zeros((s["n_nodes"], 3), dtype=np.float64)

    def assemble_residual(u_: np.ndarray) -> np.ndarray:
        f_int = ref_assemble_f_int(u_, s["coords"], s["conn"], s["lam"], s["mu"])
        return s["f_ext"] - f_int

    def tangent_mv(u_: np.ndarray, v: np.ndarray) -> np.ndarray:
        return _raw_global_matvec(u_, v, s["coords"], s["conn"], s["lam"], s["mu"])

    result = newton_solve(
        assemble_residual=assemble_residual,
        tangent_matvec=tangent_mv,
        u=u,
        bc_mask=s["bc_mask"],
        linear_solver=linear_solver,
        config=NewtonConfig(),
    )
    return result, u


