"""Task P6-3: Add a single stable integration test for `algo2code` -> PCG -> Newton plumbing.

Phase 6 (R5.3) — integration-tier acceptance: prove that a PCG path generated by
the `algo2code` pipeline can be plugged into `mechdsl.solver.newton.newton_solve`
through `LinearSolverInterface` (added in P6-1) while the imported scipy CG path
remains the default fallback (preserved in P6-2). This task establishes the
single, stable integration point between the two monorepo packages — it does
not attempt broader algo2code substitution (radial-return etc., deferred per
P6-4).

Tier: integration

Acceptance criteria:
  1. P6-3-c1: Test passes without requiring broader algo2code substitution.
     The generated PCG is the *only* algo2code-derived component exercised;
     residual / tangent assembly use the existing handwritten reference path.
  2. P6-3-c2: All deliverables for P6-3 are in place at the listed surfaces
     (targeted integration tests under
     `packages/mechdsl-core/tests/plan_tests/recovery_plan_latex_contract/`).
  3. No regressions on the existing test suite (the full plumbing is exercised
     end-to-end via `newton_solve` with the generated PCG; the imported scipy
     CG default still works in the rest of the suite).

Verification chain (executable spec for the eventual implementation):
  ProblemIR (small linear-elastic Hex8 patch)
      -> ElementIR (lowering)
      -> handwritten reference residual + tangent matvec
      -> `algo2code` parses the PCG algpseudocode source
      -> `algo2code` taichi_codegen emits a `solve(matvec, b, x0, tol, maxit)`
         function satisfying `mechdsl.solver.import_adapter.LinearSolverInterface`
      -> `newton_solve(..., linear_solver=<generated PCG adapter>)`
      -> converged Newton solution agreeing with the scipy-CG fallback
         within the project tolerance (07-CONVENTIONS §6: max diff < 1e-10).

Implementation note (P6-1 outcome): the canonical PCG LaTeX in
:mod:`algo2code.library.pcg` cannot currently be consumed by
``algo2code.algo_parser`` / ``taichi_codegen.generate`` (the multi-letter
scratch identifier ``pq`` parses as ``p * q``). P6-1 therefore ships
:class:`mechdsl.solver.import_adapter.Algo2CodePCGSolver` — a verbatim,
line-by-line Python translation of ``PCG_ALGORITHM_LATEX`` — as the
algo2code-derived component. P6-3 exercises that adapter directly; calling
the generic algo2code parser/codegen on this LaTeX would fail. The two are
kept in sync by ``test_p6_1.py``.
"""

