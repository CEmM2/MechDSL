class TestP6_3:
    """Tests for Task P6-3: stable algo2code -> PCG -> Newton integration test."""

    @pytest.mark.integration
    def test_algo2code_generated_pcg_drives_newton_to_convergence(self) -> None:
        """P6-3-c1: Test passes without requiring broader algo2code substitution.

        Plumbing exercised:
            ProblemIR -> ElementIR -> reference residual + tangent matvec
            -> algo2code-generated PCG (the *only* algo2code-derived component)
            -> `newton_solve(..., linear_solver=<generated PCG adapter>)`
            -> converged displacement field.

        Verification:
          - The generated PCG implements `LinearSolverInterface.solve(matvec, b,
            x0, tol, maxit) -> (x, n_iters, residual)` exactly as required by
            `mechdsl.solver.newton.newton_solve`.
          - On a small linear-elastic Hex8 patch, Newton converges in <= 2
            iterations (linear problem) to the same displacement field as the
            scipy-CG fallback, within max diff 1e-10 (07-CONVENTIONS §6).
          - No algo2code-generated residual / tangent / radial-return code is
            invoked — only the PCG seam is traversed (P6-4 explicitly defers
            broader substitution).

        Acceptance criterion text (from plan, Phase 6, R5.3, line 319):
            "Test passes without requiring broader algo2code substitution."
        """
        s = _build_small_elastic_patch()

        # --- 1. Type-level check: Algo2CodePCGSolver satisfies the protocol.
        # Structural Protocol — assignment-based duck check, same idiom used
        # by P6-1 / P6-2 tests.
        gen_solver: LinearSolverInterface = Algo2CodePCGSolver()
        assert callable(getattr(gen_solver, "solve", None))

        # --- 2. Run Newton with the generated PCG path. -------------------
        result_gen, u_gen = _newton_run_with(s, Algo2CodePCGSolver())
        assert result_gen.converged, (
            f"Newton did not converge with generated PCG: "
            f"iters={result_gen.n_iterations}, "
            f"final ||R||={result_gen.residual_history[-1]:.3e}"
        )
        # Linear problem: should converge within a couple of iterations.
        assert result_gen.n_iterations <= 5, (
            f"Newton with generated PCG took {result_gen.n_iterations} iters "
            "on a near-linear problem (expected <= 5)."
        )

        # --- 3. Run Newton with the imported scipy fallback. --------------
        result_ref, u_ref = _newton_run_with(s, ScipyCGSolver())
        assert result_ref.converged, (
            f"Newton did not converge with ScipyCGSolver fallback: "
            f"iters={result_ref.n_iterations}, "
            f"final ||R||={result_ref.residual_history[-1]:.3e}"
        )

        # --- 4. Generated and fallback paths agree on the displacement. ---
        # 07-CONVENTIONS §6 documents 1e-10 as the generated-vs-reference
        # tolerance. Both paths solve the same linear system with relative
        # CG tolerance 1e-10 (NewtonConfig default), so this should hold.
        max_abs_diff = float(np.max(np.abs(u_gen - u_ref)))
        assert max_abs_diff < 1e-10, (
            f"Generated PCG and ScipyCG Newton solutions diverge: "
            f"max |u_gen - u_ref| = {max_abs_diff:.3e} (must be < 1e-10)."
        )

        # --- 5. Final residual must be below the relative Newton tolerance.
        cfg = NewtonConfig()
        # Both runs share the same first-iteration residual norm because
        # they start from u=0 with identical assembly callbacks.
        assert result_gen.residual_history[-1] <= cfg.tol * result_gen.residual_history[0], (
            "Generated PCG run did not satisfy ||R||_final <= tol * ||R_0||."
        )

        # --- 6. The integration-layer hook resolves to the generated solver
        #        when mode='generated' is selected explicitly. Re-run Newton
        #        through that path to prove `select_linear_solver` is a real
        #        seam, not a stub re-export.
        gen_via_integration = select_linear_solver("generated")
        assert isinstance(gen_via_integration, Algo2CodePCGSolver)
        result_via_integration, u_via_integration = _newton_run_with(s, gen_via_integration)
        assert result_via_integration.converged
        assert float(np.max(np.abs(u_via_integration - u_gen))) < 1e-12, (
            "select_linear_solver('generated') Newton run disagrees with direct adapter."
        )

        # --- 7. Sanity: the canonical algpseudocode source is reachable
        #        through the algo2code interface hook (binds `mechdsl-core`
        #        to the algo2code package the way P6-1 specified).
        assert get_pcg_algorithm_latex() == PCG_ALGORITHM_LATEX
        assert "algorithm pcg" in PCG_ALGORITHM_LATEX
        # The adapter holds the same canonical text it consumed at construction.
        assert Algo2CodePCGSolver().algorithm_source == PCG_ALGORITHM_LATEX

    @pytest.mark.integration
    def test_deliverables_present_at_surfaces(self) -> None:
        """P6-3-c2: All deliverables for P6-3 are in place at the listed surfaces.

        Plumbing exercised: filesystem-level structural check that the
        targeted integration test lives at the surface named in the plan
        (`packages/mechdsl-core/tests/plan_tests/recovery_plan_latex_contract/`),
        and that it imports the seam introduced in P6-1
        (`mechdsl.solver.import_adapter.LinearSolverInterface`) plus the
        algo2code generation entry point.

        Verification chain:
          - This file exists at the canonical plan-test surface.
          - The real implementation imports `LinearSolverInterface` from
            `mechdsl.solver.import_adapter` and the algo2code interface
            hook (`PCG_ALGORITHM_LATEX`).
          - `newton_solve` is invoked with the generated PCG adapter (proving
            the seam is a real integration point, not a stub re-export).

        Acceptance criterion text (from plan, Phase 6, R5.3, line 319,
        deliverables column "targeted integration tests"):
            "All deliverables for P6-3 are in place at the surfaces listed."
        """
        # --- 1. This file lives at the canonical plan-test surface. ------
        this_file = Path(__file__).resolve()
        rel = this_file.relative_to(this_file.parents[5])
        # Repo-relative POSIX form so the assertion is portable across OS.
        rel_posix = rel.as_posix()
        assert rel_posix == (
            "packages/mechdsl-core/tests/plan_tests/recovery_plan_latex_contract/test_p6_3.py"
        ), f"Test file is at the wrong surface: {rel_posix}"

        # --- 2. Required surfaces are reachable + callable. --------------
        assert callable(Algo2CodePCGSolver), "Algo2CodePCGSolver must be importable + callable"
        assert callable(select_linear_solver), "select_linear_solver must be importable + callable"
        assert callable(newton_solve), "newton_solve must be importable + callable"
        assert isinstance(PCG_ALGORITHM_LATEX, str) and PCG_ALGORITHM_LATEX, (
            "PCG_ALGORITHM_LATEX must be a non-empty string (canonical algpseudocode)."
        )

        # --- 3. Mode-selector wiring is the P6-2 invariant. --------------
        # 'generated' -> Algo2CodePCGSolver
        gen = select_linear_solver("generated")
        assert isinstance(gen, Algo2CodePCGSolver)
        # 'fallback' -> ScipyCGSolver (the imported, stable path; default).
        fb = select_linear_solver("fallback")
        assert isinstance(fb, ScipyCGSolver)
        # Default (no arg) is still the fallback — P6-2 invariant.
        assert isinstance(select_linear_solver(), ScipyCGSolver)

        # --- 4. AST scan: this file actually invokes ``newton_solve`` with
        #        ``linear_solver=`` pointing at an Algo2CodePCGSolver. This
        #        guards against future refactors that drop the call site
        #        and silently turn the integration test into a no-op.
        helper_src = inspect.getsource(_newton_run_with)
        helper_tree = ast.parse(helper_src)
        found_kwarg = False
        for node in ast.walk(helper_tree):
            if not isinstance(node, ast.Call):
                continue
            func = node.func
            # Match `newton_solve(...)` calls (bare name).
            if not (isinstance(func, ast.Name) and func.id == "newton_solve"):
                continue
            for kw in node.keywords:
                if kw.arg == "linear_solver":
                    found_kwarg = True
                    break
            if found_kwarg:
                break
        assert found_kwarg, (
            "P6-3 integration test must invoke newton_solve(..., "
            "linear_solver=<adapter>); _newton_run_with helper has lost "
            "the kwarg, breaking the seam under test."
        )

        # The c1 test routes the generated solver through the helper, so
        # confirm the helper's signature accepts a LinearSolverInterface.
        sig = inspect.signature(_newton_run_with)
        assert "linear_solver" in sig.parameters

        # --- 5. Type-level check: the generated solver satisfies the
        #        protocol introduced in P6-1.
        gen_typed: LinearSolverInterface = Algo2CodePCGSolver()
        assert callable(getattr(gen_typed, "solve", None))
